"""Regenerate src/ui/icon_data.rs from the Python icon table (see gen_i18n.py).

The table is read with `ast` so PySide6 does not need to be installed.
"""
import ast
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
tree = ast.parse((ROOT / "eyecare/ui/icons.py").read_text(encoding="utf-8"))
table = next(ast.literal_eval(n.value) for n in tree.body
             if isinstance(n, ast.Assign) and getattr(n.targets[0], "id", "") == "_P")
out = ("//! Lucide-style outline icons (24x24 grid). Generated by `tools/gen_icons.py` from the Python app.\n\n"
       "pub static ICONS: &[(&str, &str)] = &[\n")
for k, v in sorted(table.items()):
    out += f'    ("{k}", r##"{v}"##),\n'
(ROOT / "rust/src/ui/icon_data.rs").write_text(out + "];\n", encoding="utf-8")
print(len(table), "icons")
