"""Generate src/common/i18n_strings.rs from the Python translation table.

Run from the repository root:  python rust/tools/gen_i18n.py
Once the Rust app fully replaces the Python one, edit the generated file (or this
script's output) directly and delete this tool.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from eyecare.core import i18n  # noqa: E402


def lit(text: str) -> str:
    out = []
    for ch in text:
        if ch in '\\"':
            out.append("\\" + ch)
        elif ch == "\n":
            out.append("\\n")
        elif ord(ch) < 32 or 0x200B <= ord(ch) <= 0x200F or 0x2028 <= ord(ch) <= 0x202F or ord(ch) == 0xFEFF:
            out.append("\\u{%x}" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def table(name: str, data: dict) -> str:
    rows = "".join(f"    ({lit(k)}, {lit(v)}),\n" for k, v in sorted(data.items()))
    return f"pub static {name}: &[(&str, &str)] = &[\n{rows}];\n\n"


text = ("//! Generated by `rust/tools/gen_i18n.py` from the Python translation table. Sorted by key.\n\n"
        + table("EN", i18n.STRINGS["en"]) + table("FA", i18n.STRINGS["fa"])).rstrip() + "\n"
(ROOT / "rust/src/common/i18n_strings.rs").write_text(text, encoding="utf-8")
print("wrote", len(i18n.STRINGS["en"]), "keys")
